// Уведомления, настройки и администраторы.
import { openSection } from "../lib/ui.mjs";

const h2 = (page, name) => page.getByRole("heading", { name, level: 2 });

export default {
  title: "Уведомления и настройки",
  subtitle: "Сообщения сотрудникам, пороги загрузки, GPS и доступ администраторов",
  start: "/admin",
  intro: "В этом ролике — как отправить сообщение сотрудникам и какие настройки стоит проверить перед запуском.",
  steps: [
    {
      say: "Откройте «Уведомления». Сообщение приходит в приложение и, если сотрудник разрешил, push-уведомлением на телефон.",
      do: (d) => openSection(d, "Уведомления"),
    },
    {
      say: "Выберите, кому: пассажирам или водителям конкретного маршрута, всем пассажирам или всем водителям. Для аудитории маршрута выберите сам маршрут.",
      do: async (d) => {
        await d.select(d.page.getByRole("combobox", { name: "Кому" }), { label: "Пассажирам маршрута" });
        await d.select(d.page.getByRole("combobox", { name: /^Маршрут/ }), { label: "№1 · утро" });
      },
    },
    {
      say: "Заголовок — коротко, текст — подробно. Нажимаем «Отправить».",
      do: async (d) => {
        await d.type(d.page.getByRole("textbox", { name: "Заголовок" }), "Изменение расписания");
        await d.type(d.page.getByRole("textbox", { name: "Текст" }), "С понедельника рейс 08:00 отправляется в 08:10.", { delay: 35 });
        await d.click(d.page.getByRole("button", { name: "Отправить" }));
        await d.wait(1300);
      },
    },
    {
      say: "Ниже — история рассылок с числом получателей. Часть записей создаёт сама система: отмены рейсов, изменения маршрутов, подъезд транспорта.",
      do: async (d) => {
        await d.highlight(d.page.getByRole("table").first());
      },
    },
    {
      say: "Теперь «Настройки». Значения по умолчанию разумные, но перед запуском их стоит просмотреть.",
      do: async (d) => {
        await d.unhighlight();
        await openSection(d, "Настройки");
      },
    },
    {
      say: "Пороги загрузки решают, когда рейс и маршрут считаются перегруженными или недозагруженными. От них зависит, что попадёт в блок «Требует решения». Меняйте их редко и осознанно.",
      do: async (d) => {
        await d.highlight(h2(d.page, "Пороги загрузки").locator(".."));
      },
    },
    {
      say: "«Мониторинг и GPS»: на каком расстоянии от линии машина считается сошедшей с маршрута, через сколько минут без координат поднимать тревогу и за сколько минут предупреждать пассажира о подъезде.",
      do: async (d) => {
        await d.unhighlight();
        await d.moveTo(h2(d.page, "Мониторинг и GPS"));
        await d.highlight(h2(d.page, "Мониторинг и GPS").locator(".."));
      },
    },
    {
      say: "«Табель водителей»: окна утренней и вечерней отметки, радиус точки сканирования и список праздников.",
      do: async (d) => {
        await d.unhighlight();
        await d.moveTo(h2(d.page, "Табель водителей"));
        await d.highlight(h2(d.page, "Табель водителей").locator(".."));
      },
    },
    {
      say: "Здесь же вы меняете свой пароль. Каждый блок сохраняется своей кнопкой.",
      do: async (d) => {
        await d.unhighlight();
        await d.moveTo(h2(d.page, "Пароль администратора"));
      },
    },
    {
      say: "И последнее — «Администраторы». Создавать других администраторов, блокировать их и сбрасывать им пароли может только суперадминистратор.",
      do: async (d) => {
        await openSection(d, "Администраторы");
        await d.moveTo(d.page.getByRole("button", { name: /Добавить администратора/ }));
      },
    },
  ],
  outro: "Настройки проверены. В последнем ролике — табель водителей.",
  outroCard: "Следующий ролик — табель водителей",
};
