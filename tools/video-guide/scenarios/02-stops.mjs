// Справочник остановок: добавить на карте, поправить, отключить.
import { openSection, row } from "../lib/ui.mjs";

const map = (page) => page.locator(".leaflet-container").first();

export default {
  title: "Остановки",
  subtitle: "Шаг 1 из 7: точки, где сотрудники садятся и выходят",
  start: "/admin",
  intro: "Учёт с нуля начинается с остановок. Остановка — это точка, где люди садятся и выходят. Одну и ту же остановку могут использовать несколько маршрутов.",
  steps: [
    {
      say: "Откройте «Справочники», «Остановки». Слева — форма, справа — карта, ниже — таблица всех остановок.",
      do: (d) => openSection(d, "Остановки"),
    },
    {
      say: "Координаты вводить не нужно. Есть три способа поставить точку. Первый — поле «Найти место»: введите название или адрес, выберите вариант из списка, и точка встанет сама, а название и адрес подставятся.",
      do: async (d) => {
        await d.highlight(d.page.getByRole("combobox", { name: /Найти место/ }));
      },
    },
    {
      say: "Второй способ — просто нажать на карту там, где садятся пассажиры.",
      do: async (d) => {
        await d.unhighlight();
        const b = await d.box(map(d.page));
        await d.clickPoint(b.x + b.width * 0.58, b.y + b.height * 0.42);
      },
    },
    {
      say: "Точка встала, форма превратилась в «Новую остановку». Третий способ — перетащить оранжевый маркер мышью, если нужно поправить место.",
      do: async (d) => {
        await d.highlight(d.page.getByRole("heading", { name: "Новая остановка" }));
      },
    },
    {
      say: "Остаётся ввести название — так остановку увидит пассажир — и, по желанию, адрес-подсказку для водителя.",
      do: async (d) => {
        await d.unhighlight();
        await d.type(d.page.getByRole("textbox", { name: /^Название/ }), "Парк культуры");
        await d.type(d.page.getByRole("textbox", { name: /^Адрес/ }), "ул. Ленина, у главного входа");
      },
    },
    {
      say: "Статус оставляем «Активна» и нажимаем «Создать остановку».",
      do: async (d) => {
        await d.click(d.page.getByRole("button", { name: "Создать остановку" }));
        await d.wait(1200);
      },
    },
    {
      say: "Остановка появилась в таблице. В колонке «Маршруты» видно, где она используется.",
      do: async (d) => {
        await d.highlight(row(d.page, "Парк культуры"));
      },
    },
    {
      say: "Чтобы поправить остановку, нажмите «Изменить» в её строке: она откроется сверху, с маркером на карте.",
      do: async (d) => {
        await d.unhighlight();
        await d.click(row(d.page, "Парк культуры").getByRole("link", { name: "Изменить" }));
        await d.page.waitForLoadState("networkidle").catch(() => {});
        await d.wait(800);
        await d.scrollTop();
      },
    },
    {
      say: "Остановку, которая уже стоит в маршруте, удалить нельзя. Если она больше не нужна, переведите статус в «Отключена»: пассажирам она предлагаться перестанет, а история поездок сохранится.",
      do: async (d) => {
        await d.highlight(d.page.getByRole("combobox", { name: "Статус" }));
      },
    },
  ],
  outro: "Остановки готовы. Следующий шаг — транспорт и водители.",
  outroCard: "Следующий ролик — транспорт и водители",
};
