/** Разделы и вопросы, адресованные одной роли. Пустые разделы отбрасываются. */
export function faqFor(role: FaqRole): FaqSection[] {
  return FAQ.map((section) => ({
    ...section,
    entries: section.entries.filter((e) => e.roles.includes(role)),
  })).filter((section) => section.entries.length > 0);
}

export function faqCount(role: FaqRole): number {
  return faqFor(role).reduce((sum, s) => sum + s.entries.length, 0);
}
